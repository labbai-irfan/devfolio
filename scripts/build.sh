#!/usr/bin/env bash
# Validates the profile JSON and compiles it into src/data/generated/ so visitors never need jq:
#   profile.sh    all profile data as Bash variables (values escaped with @sh, so sourcing is safe)
#   profile.json  minified copy used by --json
#   github.sh     GitHub stats snapshot (best effort; marked unavailable when the network is down)
#   qr.txt        QR code for the portfolio URL (only when qrencode is installed)
# Usage: build.sh [data-dir]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DATA="${1:-$ROOT/src/data}"
OUT_DIR="$DATA/generated"

bash "$ROOT/scripts/validate-data.sh" "$DATA"

# Lists become indexed arrays (Bash 3.2 has no associative arrays).
# Multi-value fields (tags, highlights, skill items) are joined with "|".
read -r -d '' PROGRAM <<'JQ' || true
def s(name; v): "\(name)=\((v // "") | tostring | @sh)";
def a(name; xs):
  "\(name)=(\((xs // []) | map((. // "") | if type == "array" then join("|") else tostring end | @sh) | join(" ")))";

$profile[0] as $p | $skills[0] as $sk | $projects[0] as $pr
| $experience[0] as $ex | $education[0] as $ed | $certifications[0] as $ce
| ([ $ex[] | select(.start | tostring | test("^[0-9]{4}")) | {d: .start, k: "Work", t: "\(.role) at \(.company)"} ]
   + [ $ed[] | select(.start | tostring | test("^[0-9]{4}")) | {d: .start, k: "Study", t: "\(.degree), \(.institution)"} ]
   + [ $ce[] | select(.date | tostring | test("^[0-9]{4}")) | {d: .date, k: "Certification", t: .name} ]
   | sort_by(.d) | reverse) as $tl
| "# GENERATED by scripts/build.sh from src/data/*.json. Do not edit."
, "# shellcheck shell=bash disable=SC2034"
, s("PROFILE_NAME"; $p.name)
, s("PROFILE_TITLE"; $p.title)
, s("PROFILE_TAGLINE"; $p.tagline)
, a("PROFILE_ABOUT"; $p.about)
, s("PROFILE_LOCATION"; $p.location)
, s("PROFILE_AVAILABILITY"; $p.availability)
, s("PROFILE_URL_PORTFOLIO"; $p.links.portfolio)
, s("PROFILE_URL_GITHUB"; $p.links.github)
, s("PROFILE_URL_LINKEDIN"; $p.links.linkedin)
, s("PROFILE_EMAIL"; $p.contact.email)
, s("PROFILE_WHATSAPP"; $p.contact.whatsapp)
, s("PROFILE_RESUME_PDF"; $p.resume.pdf_url)
, s("PROFILE_RESUME_VIEW"; $p.resume.view_url)
, s("PROFILE_GITHUB_USER"; $p.github_username)
, a("SKILL_CATEGORY"; $sk | map(.category))
, a("SKILL_ITEMS"; $sk | map(.items))
, a("PROJECT_NAME"; $pr | map(.name))
, a("PROJECT_DESC"; $pr | map(.description))
, a("PROJECT_TAGS"; $pr | map(.tags))
, a("PROJECT_URL"; $pr | map(.url))
, a("EXPERIENCE_ROLE"; $ex | map(.role))
, a("EXPERIENCE_COMPANY"; $ex | map(.company))
, a("EXPERIENCE_LOCATION"; $ex | map(.location))
, a("EXPERIENCE_START"; $ex | map(.start))
, a("EXPERIENCE_END"; $ex | map(.end))
, a("EXPERIENCE_HIGHLIGHTS"; $ex | map(.highlights))
, a("EDUCATION_DEGREE"; $ed | map(.degree))
, a("EDUCATION_INSTITUTION"; $ed | map(.institution))
, a("EDUCATION_START"; $ed | map(.start))
, a("EDUCATION_END"; $ed | map(.end))
, a("EDUCATION_NOTES"; $ed | map(.notes))
, a("CERT_NAME"; $ce | map(.name))
, a("CERT_ISSUER"; $ce | map(.issuer))
, a("CERT_DATE"; $ce | map(.date))
, a("CERT_URL"; $ce | map(.url))
, a("TIMELINE_DATE"; $tl | map(.d))
, a("TIMELINE_KIND"; $tl | map(.k))
, a("TIMELINE_TEXT"; $tl | map(.t))
JQ

DATA_ARGS=(
  --slurpfile profile "$DATA/profile.json"
  --slurpfile skills "$DATA/skills.json"
  --slurpfile projects "$DATA/projects.json"
  --slurpfile experience "$DATA/experience.json"
  --slurpfile education "$DATA/education.json"
  --slurpfile certifications "$DATA/certifications.json"
)

mkdir -p "$OUT_DIR"
tmp="$(mktemp)"
gh_tmp="$(mktemp)"
trap 'rm -f "$tmp" "$gh_tmp"' EXIT

# tr strips CR: jq.exe on Windows can emit CRLF, which would corrupt the values.
jq -n -r "${DATA_ARGS[@]}" "$PROGRAM" | tr -d '\r' >"$tmp"
mv "$tmp" "$OUT_DIR/profile.sh"
printf 'Built %s\n' "$OUT_DIR/profile.sh"

jq -n -c "${DATA_ARGS[@]}" '{
  profile: $profile[0], skills: $skills[0], projects: $projects[0],
  experience: $experience[0], education: $education[0], certifications: $certifications[0]
}' | tr -d '\r' >"$OUT_DIR/profile.json"
printf 'Built %s\n' "$OUT_DIR/profile.json"

# GitHub snapshot. A failure is not a build failure: the app shows the snapshot or says it is unavailable.
PORTFOLIO="$(jq -r '.links.portfolio' "$DATA/profile.json")"
gh_user="$(jq -r '.github_username' "$DATA/profile.json")"
source "$ROOT/src/services/github_api.sh"
if github_fetch_shell "$gh_user" "$gh_tmp"; then
  {
    printf '# GENERATED by scripts/build.sh from the GitHub API. Do not edit.\n'
    printf '# shellcheck shell=bash disable=SC2034\n'
    printf 'GH_SOURCE=snapshot\nGH_AS_OF=%s\n' "$(date +%Y-%m-%d)"
    cat "$gh_tmp"
  } >"$OUT_DIR/github.sh"
  printf 'Built %s (GitHub snapshot)\n' "$OUT_DIR/github.sh"
else
  {
    printf '# GENERATED by scripts/build.sh. Do not edit.\n'
    printf '# shellcheck shell=bash disable=SC2034\n'
    printf "GH_SOURCE=none\nGH_ERROR='%s'\n" "$GH_ERROR"
  } >"$OUT_DIR/github.sh"
  printf 'GitHub snapshot skipped: %s\n' "$GH_ERROR"
fi

# QR code for the portfolio, only when qrencode is available and the URL is real (not a placeholder).
if command -v qrencode >/dev/null 2>&1 && [[ "$PORTFOLIO" == https://* ]]; then
  qrencode -t UTF8 -o "$OUT_DIR/qr.txt" "$PORTFOLIO"
  printf 'Built %s\n' "$OUT_DIR/qr.txt"
else
  rm -f "$OUT_DIR/qr.txt"
fi
