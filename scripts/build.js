#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dataDir = path.join(root, 'src', 'data');

function readJson(filename) {
  return JSON.parse(fs.readFileSync(path.join(dataDir, filename), 'utf8'));
}

const p = readJson('profile.json');
const sk = readJson('skills.json');
const pr = readJson('projects.json');
const ex = readJson('experience.json');
const ed = readJson('education.json');
const ce = readJson('certifications.json');

function shEscape(val) {
  if (val === null || val === undefined) return "''";
  const s = String(val);
  return "'" + s.replace(/'/g, "'\\''") + "'";
}

function s(name, val) { return `${name}=${shEscape(val || '')}`; }
function a(name, arr) {
  const items = (arr || []).map(item => {
    if (Array.isArray(item)) return shEscape(item.join('|'));
    return shEscape(item || '');
  });
  return `${name}=(${items.join(' ')})`;
}

const tl = [];
for (const item of (ex || [])) {
  if (item.start && /^[0-9]{4}/.test(String(item.start))) {
    tl.push({
      d: String(item.start),
      e: String(item.end || 'present'),
      k: 'Work',
      title: String(item.role || ''),
      subtitle: String(item.company || ''),
      loc: String(item.location || ''),
      desc: Array.isArray(item.highlights) && item.highlights.length > 0 ? item.highlights[0] : ''
    });
  }
}
for (const item of (ed || [])) {
  if (item.start && /^[0-9]{4}/.test(String(item.start))) {
    tl.push({
      d: String(item.start),
      e: String(item.end || 'present'),
      k: 'Education',
      title: String(item.degree || ''),
      subtitle: String(item.institution || ''),
      loc: '',
      desc: String(item.notes || '')
    });
  }
}
for (const item of (ce || [])) {
  if (item.date && /^[0-9]{4}/.test(String(item.date))) {
    tl.push({
      d: String(item.date),
      e: '',
      k: 'Honor',
      title: String(item.name || ''),
      subtitle: String(item.issuer || ''),
      loc: '',
      desc: item.url ? item.url : ''
    });
  }
}
tl.sort((x, y) => (x.d < y.d ? 1 : x.d > y.d ? -1 : 0));

const lines = [
  '# GENERATED by scripts/build.js from src/data/*.json. Do not edit.',
  '# shellcheck shell=bash disable=SC2034',
  s('PROFILE_NAME', p.name),
  s('PROFILE_TITLE', p.title),
  s('PROFILE_TAGLINE', p.tagline),
  a('PROFILE_ABOUT', p.about),
  s('PROFILE_LOCATION', p.location),
  s('PROFILE_AVAILABILITY', p.availability),
  s('PROFILE_URL_PORTFOLIO', p.links?.portfolio),
  s('PROFILE_URL_GITHUB', p.links?.github),
  s('PROFILE_URL_LINKEDIN', p.links?.linkedin),
  s('PROFILE_EMAIL', p.contact?.email),
  s('PROFILE_WHATSAPP', p.contact?.whatsapp),
  s('PROFILE_RESUME_PDF', p.resume?.pdf_url),
  s('PROFILE_RESUME_VIEW', p.resume?.view_url),
  s('PROFILE_GITHUB_USER', p.github_username),
  s('PROFILE_GH_COMMITS', p.github_stats?.total_commits || '350+'),
  s('PROFILE_GH_PRS', p.github_stats?.pull_requests || '25+'),
  s('PROFILE_GH_CONTRIBS', p.github_stats?.contributions || '400+'),
  a('SKILL_CATEGORY', sk.map(x => x.category)),
  a('SKILL_ITEMS', sk.map(x => x.items)),
  a('PROJECT_NAME', pr.map(x => x.name)),
  a('PROJECT_CATEGORY', pr.map(x => x.category || 'Software Engineering')),
  a('PROJECT_DESC', pr.map(x => x.description)),
  a('PROJECT_TAGS', pr.map(x => x.tags)),
  a('PROJECT_URL', pr.map(x => x.url)),
  a('PROJECT_FEATURED', pr.map(x => (x.featured ? '1' : '0'))),
  a('PROJECT_STATUS', pr.map(x => x.status || 'Completed')),
  a('EXPERIENCE_ROLE', ex.map(x => x.role)),
  a('EXPERIENCE_COMPANY', ex.map(x => x.company)),
  a('EXPERIENCE_LOCATION', ex.map(x => x.location)),
  a('EXPERIENCE_START', ex.map(x => x.start)),
  a('EXPERIENCE_END', ex.map(x => x.end)),
  a('EXPERIENCE_HIGHLIGHTS', ex.map(x => x.highlights)),
  a('EDUCATION_DEGREE', ed.map(x => x.degree)),
  a('EDUCATION_INSTITUTION', ed.map(x => x.institution)),
  a('EDUCATION_START', ed.map(x => x.start)),
  a('EDUCATION_END', ed.map(x => x.end)),
  a('EDUCATION_NOTES', ed.map(x => x.notes)),
  a('CERT_NAME', ce.map(x => x.name)),
  a('CERT_ISSUER', ce.map(x => x.issuer)),
  a('CERT_DATE', ce.map(x => x.date)),
  a('CERT_URL', ce.map(x => x.url)),
  a('TIMELINE_DATE', tl.map(x => x.d)),
  a('TIMELINE_END', tl.map(x => x.e)),
  a('TIMELINE_KIND', tl.map(x => x.k)),
  a('TIMELINE_TITLE', tl.map(x => x.title)),
  a('TIMELINE_SUBTITLE', tl.map(x => x.subtitle)),
  a('TIMELINE_LOC', tl.map(x => x.loc)),
  a('TIMELINE_DESC', tl.map(x => x.desc))
];

fs.writeFileSync(path.join(dataDir, 'profile.sh'), lines.join('\n') + '\n', 'utf8');
console.log('src/data/profile.sh compiled successfully!');
